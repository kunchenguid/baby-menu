// Bundles the clean-room ACP adapters into self-contained JS files under
// out/adapters/. Each adapter is spawned by acpx as a separate `node <file>`
// process and speaks ACP over stdio, so it must carry its own dependencies
// (@agentclientprotocol/sdk + zod) - a standalone node process cannot require
// modules from inside the packaged app.asar. esbuild bundles everything except
// Node built-ins into one file per adapter.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const adapters = ["claude", "codex"];

await build({
  entryPoints: Object.fromEntries(
    adapters.map((name) => [`adapters/${name}/index`, resolve(root, `src/adapters/${name}/index.ts`)]),
  ),
  outdir: resolve(root, "out"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  // Emit .mjs so the file is treated as ESM unconditionally. The adapters run as
  // standalone processes via Electron-as-node (ELECTRON_RUN_AS_NODE), which loads
  // a `.js` file as CommonJS even under a `type:module` package - breaking the
  // ESM SDK. `.mjs` removes that ambiguity. Layout: out/adapters/<name>/index.mjs.
  outExtension: { ".js": ".mjs" },
  // Node built-ins only; everything else (SDK, zod) is bundled in.
  banner: {
    js: "// Generated by scripts/build-adapters.mjs - clean-room ACP adapter (do not edit).",
  },
  logLevel: "info",
});

console.log("Built ACP adapters:", adapters.map((n) => `out/adapters/${n}/index.mjs`).join(", "));
